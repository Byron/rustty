#!/usr/bin/env python3
"""Generate the checked Rust command registry from this checkout's C tables."""

from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import re

from source_paths import TMUXX, c_source
OUTPUT = TMUXX / "crates/tmuxx-command/src/metadata.rs"
STRING = r'"(?:\\.|[^"\\])*"'
# These C handlers resolve their target themselves ("-t is special").
MANUAL_SELECTOR_FLAGS = {
    "attach-session": "t",
    "switch-client": "t",
    "link-window": "t",
    "move-window": "t",
}


def strings(expression, macros, active=()):
    if expression.strip() == "NULL":
        return ""
    result = []
    for token in re.findall(STRING + r"|[A-Za-z_]\w*|\S", expression):
        if token.startswith('"'):
            result.append(ast.literal_eval(token))
        elif token in macros and token not in active:
            result.append(strings(macros[token], macros, (*active, token)))
        else:
            raise ValueError(f"unresolved string token {token!r} in {expression!r}")
    return "".join(result)


def selector_flags(fields, flags, name):
    selectors = set(MANUAL_SELECTOR_FLAGS.get(name, ""))
    for role in ("source", "target"):
        if role not in fields:
            continue
        match = re.fullmatch(r"\{\s*'([A-Za-z0-9])'\s*,\s*CMD_FIND_(?:SESSION|WINDOW|PANE)\s*,.*\}",
                             fields[role].strip(), re.S)
        if not match:
            raise ValueError(f"unrecognized {role} selector in {name}")
        selectors.add(match[1])
    for marker, flag in (("CMD_CLIENT_CFLAG", "c"), ("CMD_CLIENT_TFLAG", "t")):
        if marker in fields["flags"]:
            selectors.add(flag)
    if any(flag + ":" not in flags for flag in selectors):
        raise ValueError(f"selector without argument flag in {name}")
    return "".join(sorted(selectors))


def generate(root=None):
    root = c_source() if root is None else root
    sources = {path.name: path.read_text(encoding="utf-8") for path in sorted(root.glob("cmd-*.c"))}
    macros = {}
    for source in [(root / "tmux.h").read_text(encoding="utf-8"), *sources.values()]:
        source = source.replace("\\\n", "")
        for name, value in re.findall(r"^#define\s+(\w+)[ \t]+([^\n]*)", source, re.M):
            macros[name] = value.strip()
    entries = {}
    for filename, source in sources.items():
        for identifier, body in re.findall(
            r"const struct cmd_entry (\w+) = \{(.*?)\n\};", source, re.S
        ):
            body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
            fields = dict(re.findall(r"\.(\w+)\s*=\s*(.*?),(?=\s*\.\w+\s*=)", body, re.S))
            args = re.fullmatch(r"\{\s*(" + STRING + r")\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(\w+)\s*\}", fields["args"])
            if not args:
                raise ValueError(f"unrecognized args in {identifier}")
            entry = {key: strings(fields.get(key, "NULL"), macros)
                     for key in ("name", "alias", "usage", "description")}
            entry.update(flags=strings(args[1], macros), minimum=int(args[2]), maximum=int(args[3]),
                         after_hook="CMD_AFTERHOOK" in fields["flags"],
                         readonly="CMD_READONLY" in fields["flags"],
                         starts_server="CMD_STARTSERVER" in fields["flags"], source=filename)
            entry["selector_flags"] = selector_flags(fields, entry["flags"], entry["name"])
            entries[identifier] = entry
    table = (root / "cmd.c").read_text(encoding="utf-8").split("const struct cmd_entry *cmd_table[] = {", 1)[1].split("};", 1)[0]
    ordered = [entries[name] for name in re.findall(r"&(\w+)", table)]
    if not ordered or len({entry["name"] for entry in ordered}) != len(ordered):
        raise ValueError("empty or duplicate command registry")
    lines = ["// Generated by rust/conformance/generate_command_metadata.py; do not edit.",
             "// C command registration order is observable in list-commands and ambiguity errors.",
             "#[rustfmt::skip]", "pub const COMMANDS: &[CommandSpec] = &["]
    for entry in ordered:
        fields = []
        for key, value in entry.items():
            if key == "maximum":
                value = "None" if value == -1 else f"Some({value})"
            elif isinstance(value, bool):
                value = str(value).lower()
            elif isinstance(value, str):
                value = json.dumps(value, ensure_ascii=False)
            fields.append(f"{key}: {value}")
        lines.append("    CommandSpec { " + ", ".join(fields) + " },")
    return "\n".join([*lines, "];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on unreviewed source metadata drift")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            parser.exit(1, "C command metadata changed; regenerate and review metadata.rs and parity coverage.\n")
    else:
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
