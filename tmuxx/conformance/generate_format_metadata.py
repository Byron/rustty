#!/usr/bin/env python3
"""Generate the ordered C format callback keys used by display-message -a."""
import argparse
import json
import re
from pathlib import Path
from source_paths import TMUXX, c_source
OUTPUT = TMUXX / 'crates/tmuxx-core/src/format_metadata.rs'
def generate(root=None):
    root = c_source() if root is None else root
    table = (root / 'format.c').read_text(encoding="utf-8").split('static const struct format_table_entry format_table[] = {', 1)[1].split('\n};', 1)[0]
    keys = re.findall(r'\{\s*"([^"]+)",\s*FORMAT_TABLE_(?:STRING|TIME)', table)
    if not keys or keys != sorted(set(keys)):
        raise ValueError('format callback registry must be nonempty, sorted and unique')
    return '// Generated by rust/conformance/generate_format_metadata.py; do not edit.\n' + 'pub const FORMAT_KEYS: &[&str] = &[\n' + ''.join(f'    {json.dumps(key)},\n' for key in keys) + '];\n'
def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != result:
            parser.exit(1, 'C format callbacks changed; regenerate and review format metadata and conformance.\n')
    else:
        OUTPUT.write_text(result)
if __name__ == '__main__': main()
